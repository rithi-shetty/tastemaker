"""Run every experiment and write the results the README and demo use.

    python -m tastemaker.pipeline            # full run, about 5 minutes
    python -m tastemaker.pipeline --quick    # smaller run for CI

Outputs: reports/results.json, reports/figures/*.png, web/data.js
"""
from __future__ import annotations

import argparse
import json
import time
from dataclasses import replace
from pathlib import Path

import numpy as np

from . import experiments as ex
from . import figures
from .config import BASE, CATEGORIES, SCENARIO_LABELS
from .policies import LABELS

ROOT = Path(__file__).resolve().parent.parent


def _clean(o):
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, np.integer):
        return int(o)
    if isinstance(o, (np.floating, float)):
        return round(float(o), 5)
    if isinstance(o, np.ndarray):
        return _clean(o.tolist())
    return o


def main(quick: bool = False) -> dict:
    t0 = time.time()
    say = lambda m: print(f"[{time.time() - t0:6.1f}s] {m}", flush=True)
    w = replace(BASE, n_users=1000) if quick else BASE
    say("Comparing policies")
    cmp = ex.compare(w, seeds=range(1 if quick else 3))
    say("Short vs long tests")
    svl = ex.short_vs_long(cmp)
    say("Cold start")
    cold = ex.cold_start(w)
    say("Diversity dial")
    dial = ex.diversity_dial(w, penalties=(0, 0.25, 1.0) if quick else (0, 0.06, 0.12, 0.25, 0.5, 1.0, 2.0),
                             seeds=range(1 if quick else 2))
    say("Robustness")
    rob = ex.robustness(w, seeds=range(3 if quick else 10))
    say("Stress tests")
    stress = ex.stress_tests() if not quick else []
    for s in stress:
        s["label"] = SCENARIO_LABELS[s["scenario"]]
    say("Test power")
    power = ex.test_power(cmp, w)
    say("Persona journeys")
    jour = ex.journeys(w)
    results = _clean({
        "meta": {"version": "1.0.0", "quick": quick, "users": w.n_users, "days": w.days,
                 "cards_per_day": w.cards_per_day, "labels": LABELS},
        "compare": cmp, "short_vs_long": svl, "cold_start": cold, "diversity_dial": dial,
        "robustness": rob, "stress": stress, "power": power,
    })
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "results.json").write_text(json.dumps(results, indent=1), encoding="utf8")
    (ROOT / "web").mkdir(exist_ok=True)
    payload = {"results": results, "journeys": _clean(jour),
               "categories": [{"name": n, "emoji": e, "color": c} for n, e, c in CATEGORIES]}
    (ROOT / "web" / "data.js").write_text("// Generated by tastemaker.pipeline. Do not edit by hand.\nconst DATA = "
                                          + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
                                          encoding="utf8")
    say("Figures")
    figures.draw_all(results, ROOT / "reports" / "figures")
    figures.journey(payload["journeys"], CATEGORIES, ROOT / "docs" / "img")
    say("Done")
    return results


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    main(ap.parse_args().quick)
